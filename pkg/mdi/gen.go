//go:build ignore

// gen writes names_gen.go from md.tsv: the table Glyph looks names up in.
//
//	go run gen.go                          # names_gen.go from md.tsv
//	go run gen.go -from glyphnames.json    # md.tsv from Nerd Fonts' file, then names_gen.go
//
// glyphnames.json is Nerd Fonts' (github.com/ryanoasis/nerd-fonts, at the
// release tag the hosts' font is patched with: v3.5.1): its md-* entries
// are MDI's glyphs, md-cog_outline being MDI's cog-outline.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	from := flag.String("from", "", "Nerd Fonts' glyphnames.json, to write md.tsv from first")
	flag.Parse()
	if *from != "" {
		if err := tsvFrom(*from); err != nil {
			log.Fatal(err)
		}
	}
	if err := table(); err != nil {
		log.Fatal(err)
	}
}

// tsvFrom writes md.tsv from glyphnames.json's md-* entries.
func tsvFrom(path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var all map[string]json.RawMessage
	if err := json.Unmarshal(data, &all); err != nil {
		return err
	}
	var meta struct{ Version string }
	if err := json.Unmarshal(all["METADATA"], &meta); err != nil {
		return err
	}
	type entry struct{ name, code string }
	var md []entry
	for k, v := range all {
		name, ok := strings.CutPrefix(k, "md-")
		if !ok {
			continue
		}
		var g struct{ Code string }
		if err := json.Unmarshal(v, &g); err != nil {
			return err
		}
		md = append(md, entry{strings.ReplaceAll(name, "_", "-"), g.Code})
	}
	sort.Slice(md, func(i, j int) bool { return md[i].name < md[j].name })
	var b bytes.Buffer
	fmt.Fprintf(&b, "# The MDI glyphs of Nerd Fonts %s (glyphnames.json, md-*), by MDI's names: name, code point.\n", meta.Version)
	for _, e := range md {
		fmt.Fprintf(&b, "%s\t%s\n", e.name, e.code)
	}
	return os.WriteFile("md.tsv", b.Bytes(), 0o644)
}

// table writes names_gen.go: the names, sorted, run together in one
// string, where each ends, and each one's code point less 0xF0000 (MDI's
// plane-15 range in Nerd Fonts), all constant data, which a program that
// never calls Glyph doesn't link.
func table() error {
	f, err := os.Open("md.tsv")
	if err != nil {
		return err
	}
	defer f.Close()
	var head string
	var names []string
	var codes []int64
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") {
			head = strings.TrimSpace(strings.TrimPrefix(line, "#"))
			continue
		}
		name, code, ok := strings.Cut(line, "\t")
		if !ok {
			return fmt.Errorf("md.tsv: %q is no name and code point", line)
		}
		c, err := strconv.ParseInt(code, 16, 32)
		if err != nil || c < 0xF0000 || c > 0xFFFFF {
			return fmt.Errorf("md.tsv: %s's code point %s is not in MDI's range", name, code)
		}
		if len(names) > 0 && name <= names[len(names)-1] {
			return fmt.Errorf("md.tsv: %s is out of order", name)
		}
		names = append(names, name)
		codes = append(codes, c-0xF0000)
	}
	if err := sc.Err(); err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen.go from md.tsv; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// %s\n\npackage mdi\n\n", head)
	fmt.Fprintf(&b, "// names are the names, sorted, run together.\nconst names = \"\" +\n")
	line := ""
	for i, n := range names {
		line += n
		if len(line) >= 64 || i == len(names)-1 {
			sep := " +"
			if i == len(names)-1 {
				sep = ""
			}
			fmt.Fprintf(&b, "\t%q%s\n", line, sep)
			line = ""
		}
	}
	b.WriteString("\n// ends are where each name ends in names.\nvar ends = [...]uint32{")
	end := 0
	for i, n := range names {
		end += len(n)
		if i%12 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%d, ", end)
	}
	b.WriteString("\n}\n\n// codes are each name's code point less 0xF0000.\nvar codes = [...]uint16{")
	for i, c := range codes {
		if i%12 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%#04x, ", c)
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("names_gen.go", src, 0o644)
}
