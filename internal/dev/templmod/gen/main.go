// Command gen writes templmod's patch_gen.go from mods/templ: the patch
// the reloader overlays, and the templ version it is for (mod.md's base).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func main() {
	dir := filepath.Join("..", "..", "mods", "templ")
	patches, err := filepath.Glob(filepath.Join(dir, "*.patch"))
	if err != nil || len(patches) != 1 {
		log.Fatalf("gen: want one patch in %s, have %v (%v)", dir, patches, err)
	}
	p, err := os.ReadFile(patches[0])
	if err != nil {
		log.Fatal(err)
	}
	mod, err := os.ReadFile(filepath.Join(dir, "mod.md"))
	if err != nil {
		log.Fatal(err)
	}
	base := ""
	for _, line := range strings.Split(string(mod), "\n") {
		if v, ok := strings.CutPrefix(line, "base:"); ok {
			base = strings.TrimSpace(v)
			break
		}
	}
	if base == "" {
		log.Fatal("gen: mod.md has no base")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by templmod/gen from mods/templ. DO NOT EDIT.\n\npackage templmod\n\n")
	fmt.Fprintf(&b, "// base is the templ version the patch is for (mods/templ/mod.md).\nconst base = %q\n\n", base)
	fmt.Fprintf(&b, "// patchName is the patch's file in mods/templ.\nconst patchName = %q\n\n", filepath.Base(patches[0]))
	fmt.Fprintf(&b, "// patch is the patch, as git format-patch wrote it.\nconst patch = %s\n", strconv.Quote(string(p)))
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("patch_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
