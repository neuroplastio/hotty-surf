#!/usr/bin/env python3
"""lucide.py: lucide's icons, as Go, for ui (Icon): the inner SVG
of each icon named, read from lucide-react's ESM files (their __iconNode),
the paths lucide-react draws: the kit's ICONS, and any more named.

    lucide.py <lucide-react dir> <out.go> [<icon>...]
"""
import json, os, re, sys

# The kit's icons: a subset of Lucide's, the ones its components draw
# and a set an app commonly needs.
ICONS = """
archive arrow-down arrow-left arrow-right arrow-up arrow-up-down bell
bookmark calendar check chevron-down chevron-left chevron-right
chevron-up chevrons-left chevrons-right chevrons-up-down circle
circle-alert circle-check-big circle-help circle-off circle-plus
circle-x clock code copy download ellipsis ellipsis-vertical
external-link eye eye-off file file-plus file-text filter folder
folder-open folder-plus git-branch globe hand heart house image inbox
info layout-grid link list lock lock-open log-in log-out mail menu
message-square minus moon panel-left paperclip pause pencil play plus
refresh-cw save search send settings settings-2 share-2 sparkles square
star sun tag terminal timer trash trash-2 trending-down trending-up
triangle-alert upload user user-plus users x
""".split()

src, out, names = sys.argv[1], sys.argv[2], ICONS + sys.argv[3:]
ver = json.load(open(os.path.join(src, "package.json")))["version"]
rows = []
for n in sorted(set(names)):
    js = open(os.path.join(src, "dist", "esm", "icons", n + ".js")).read()
    body = js[js.index("__iconNode = [") + len("__iconNode = ["): js.index("];\n")]
    parts = []
    for tag, attrs in re.findall(r'\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]', body):
        kv = re.findall(r'(\w+): "([^"]*)"', attrs)
        parts.append("<" + tag + "".join(f' {k}="{v}"' for k, v in kv if k != "key") + f"></{tag}>")
    rows.append(f'\t"{n}": `{"".join(parts)}`,')
open(out, "w").write(f"""// Code generated by internal/gen/lucide.py from lucide-react {ver} (ISC). DO NOT EDIT.

package ui

// icons is each icon's inner SVG, by lucide's name.
var icons = map[string]string{{
{chr(10).join(rows)}
}}

// iconNames is the name of every icon Icon draws, sorted.
func iconNames() []string {{
\treturn []string{{
{"".join(f'{chr(9)}{chr(9)}"{n}",{chr(10)}' for n in sorted(set(names)))}\t}}
}}
""")
print(f"{len(rows)} icons from lucide-react {ver}")
