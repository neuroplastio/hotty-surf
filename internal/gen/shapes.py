#!/usr/bin/env python3
"""shapes.py: Material Symbols' shapes, as Go consts, for internal/spikeui
(Shape, Symbol): the path of each icon below, from the
@iconify-json/material-symbols package (npm pack it, check its integrity
against the registry's, and unpack it).

    npm pack @iconify-json/material-symbols@1.2.93 && mkdir x && tar xzf *.tgz -C x
    shapes.py x/package internal/spikeui/shapes_gen.go

Each shape is one path on a 24-unit grid, the Sharp variant (an alias in the
package resolves to its parent's icon); Iconify names are in the comments.
"""
import json, os, re, sys

# Go name, Iconify name. The ones the nav draws; add as apps need them.
SHAPES = [
    ("ShapeTerminal", "terminal-sharp"),
    ("ShapeAccountTree", "account-tree-sharp"),
    ("ShapePublic", "public-sharp"),
    ("ShapeDesktopWindows", "desktop-windows-outline-sharp"),
    ("ShapeGridView", "grid-view-outline-sharp"),
    ("ShapeMoreHoriz", "more-horiz-sharp"),
    ("ShapeRemove", "remove-sharp"),
]

src, out = sys.argv[1], sys.argv[2]
pkg = sys.argv[3] if len(sys.argv) > 3 else "spikeui"
ver = json.load(open(os.path.join(src, "package.json")))["version"]
d = json.load(open(os.path.join(src, "icons.json")))
icons, aliases = d["icons"], d.get("aliases", {})


def body(name):
    seen = name
    while seen not in icons:
        seen = aliases[seen]["parent"]
    b = icons[seen]["body"]
    ds = re.findall(r' d="([^"]+)"', b)
    if b.count("<path") != 1 or len(ds) != 1:
        sys.exit(f"{name}: not one path: {b}")
    return ds[0]


rows = "".join(f'\t// {g} is the {n} Material Symbol.\n\t{g} Shape = "{body(n)}"\n' for g, n in SHAPES)
named = "".join(f'\t\t{{"{g}", {g}}},\n' for g, _ in sorted(SHAPES))
open(out, "w").write(f"""// Code generated by internal/gen/shapes.py from @iconify-json/material-symbols {ver} (Apache License 2.0, Google). DO NOT EDIT.

package {pkg}

// Shape is SVG path data for a filled glyph on a 24-unit grid. The shipped
// constants are Material Symbols, Sharp; an app may supply another path.
type Shape string

const (
{rows})

// NamedShape is a Shape and its Go name.
type NamedShape struct {{
	// Name is the Go name of Shape.
	Name string
	// Shape is the named path.
	Shape Shape
}}

// Symbols returns the kit's named Material shapes in ascending Go-name
// order. The returned slice is the caller's.
func Symbols() []NamedShape {{
	return []NamedShape{{
{named}	}}
}}
""")
