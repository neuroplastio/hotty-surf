// Command uigen writes ui's components that Basecoat makes from CSS alone,
// one element each, from the table in table.go: their Props, their
// functions and their docs (ui/css_gen.go), and their markup
// (ui/css_gen.templ, which templ then generates). ui runs it with go
// generate.
//
// A component that is more than one element with its children (a native
// select's options, a range's track) is written by hand in ui; the table
// is for the ones a row can say whole.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	goSrc, err := format.Source(genGo())
	if err != nil {
		fail(err)
	}
	write(filepath.Join(dir, "css_gen.go"), goSrc)
	write(filepath.Join(dir, "css_gen.templ"), genTempl())
}

func write(path string, b []byte) {
	if err := os.WriteFile(path, b, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "uigen:", err)
	os.Exit(1)
}

const header = "// Code generated by internal/uigen from its table; DO NOT EDIT.\n\n"

// genGo is the Props, the functions and their docs.
func genGo() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package ui\n\nimport \"github.com/a-h/templ\"\n")
	for _, c := range table {
		fmt.Fprintf(&b, "\n// %sProps are %s %s's attributes.\n", c.Name, article(c.Name), c.Name)
		if c.PropsDoc != "" {
			b.WriteString("//\n")
			comment(&b, "", c.PropsDoc)
		}
		fmt.Fprintf(&b, "type %sProps struct {\n", c.Name)
		for _, f := range c.Fields {
			if f.Doc != "" {
				comment(&b, "\t", f.Doc)
			}
			fmt.Fprintf(&b, "\t%s %s\n", f.Name, f.Type)
		}
		attrsDoc := c.AttrsDoc
		if attrsDoc == "" {
			attrsDoc = fmt.Sprintf("Attrs are more attributes for the %s element: its id and handlers, through surf.On, and any other but those the component writes itself (%s), which are a fault here.", c.Tag, orList(writtenNames(c)))
		}
		comment(&b, "\t", attrsDoc)
		b.WriteString("\tAttrs templ.Attributes\n")
		comment(&b, "\t", "Class is more classes for the element, after its own.")
		b.WriteString("\tClass string\n}\n\n")
		comment(&b, "", c.Name+" "+c.Doc)
		lower := lowerName(c.Name)
		switch {
		case c.Void || c.Text != "":
			fmt.Fprintf(&b, "func %s(p %sProps) templ.Component {\n\treturn %s(p)\n}\n", c.Name, c.Name, lower)
		default:
			fmt.Fprintf(&b, "func %s(p %sProps) templ.Component {\n\treturn scoped(%s(p), %v)\n}\n", c.Name, c.Name, lower, c.Group)
		}
	}
	return b.Bytes()
}

// genTempl is the markup.
func genTempl() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package ui\n")
	for _, c := range table {
		fmt.Fprintf(&b, "\n// %s is %s's markup (Basecoat's %s.css).\n", lowerName(c.Name), c.Name, c.File)
		fmt.Fprintf(&b, "templ %s(p %sProps) {\n", lowerName(c.Name), c.Name)
		for _, ck := range c.Checks {
			fmt.Fprintf(&b, "\t{{ %s }}\n", check(c, ck))
		}
		fmt.Fprintf(&b, "\t{{ checkAttrs(ctx, %q, p.Attrs, %s) }}\n", c.Name, written(c))
		fmt.Fprintf(&b, "\t<%s\n", c.Tag)
		if c.Slot != "" {
			fmt.Fprintf(&b, "\t\tdata-slot=%q\n", c.Slot)
		}
		for _, a := range c.Attrs {
			attr(&b, c, a)
		}
		if c.Class != "" && c.Bare {
			fmt.Fprintf(&b, "\t\tclass={ join(bare(ctx, %q), p.Class) }\n", c.Class)
		} else if c.Class != "" {
			fmt.Fprintf(&b, "\t\tclass={ join(%q, p.Class) }\n", c.Class)
		} else {
			b.WriteString("\t\tif p.Class != \"\" {\n\t\t\tclass={ p.Class }\n\t\t}\n")
		}
		b.WriteString("\t\t{ p.Attrs... }\n")
		switch {
		case c.Void:
			b.WriteString("\t/>\n")
		case c.Text != "":
			fmt.Fprintf(&b, "\t>{ p.%s }</%s>\n", c.Text, c.Tag)
		default:
			fmt.Fprintf(&b, "\t>\n\t\t{ children... }\n\t</%s>\n", c.Tag)
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

func check(c Comp, ck Check) string {
	switch ck.Kind {
	case "variant":
		return fmt.Sprintf("checkVariant(ctx, %q, p.%s, %s)", c.Name, ck.Field, ck.List)
	case "size":
		return fmt.Sprintf("checkSize(ctx, %q, p.%s, %s)", c.Name, ck.Field, ck.List)
	case "call":
		return ck.List
	default:
		return fmt.Sprintf("checkEnum(ctx, %q, %q, p.%s, %s)", c.Name, ck.Field, ck.Field, ck.List)
	}
}

func attr(b *bytes.Buffer, c Comp, a Attr) {
	f := c.field(a.Field)
	switch {
	case a.Field == "" && a.Expr != "":
		fmt.Fprintf(b, "\t\tif s := %s; s != \"\" {\n\t\t\t%s={ s }\n\t\t}\n", a.Expr, a.Name)
	case a.Field == "" && a.IfUnset:
		fmt.Fprintf(b, "\t\tif _, ok := p.Attrs[%q]; !ok {\n\t\t\t%s=%q\n\t\t}\n", a.Name, a.Name, a.Value)
	case a.Field == "":
		fmt.Fprintf(b, "\t\t%s=%q\n", a.Name, a.Value)
	case f.Type == "bool" && a.Value == "":
		fmt.Fprintf(b, "\t\t%s?={ p.%s }\n", a.Name, a.Field)
	case f.Type == "bool":
		fmt.Fprintf(b, "\t\tif p.%s {\n\t\t\t%s=%q\n\t\t}\n", a.Field, a.Name, a.Value)
	case a.Default != "":
		fmt.Fprintf(b, "\t\t%s={ or(%s, %q) }\n", a.Name, str(f), a.Default)
	case a.Always:
		fmt.Fprintf(b, "\t\t%s={ %s }\n", a.Name, str(f))
	default:
		fmt.Fprintf(b, "\t\tif p.%s != \"\" {\n\t\t\t%s={ %s }\n\t\t}\n", a.Field, a.Name, str(f))
	}
}

// writtenNames is the attributes the component writes itself, which its
// Attrs may not repeat (Button's type, which Attrs replaces, aside).
func writtenNames(c Comp) []string {
	names := []string{"class"}
	if c.Slot != "" {
		names = append(names, "data-slot")
	}
	for _, a := range c.Attrs {
		if !a.IfUnset {
			names = append(names, a.Name)
		}
	}
	return names
}

// written is writtenNames as checkAttrs takes them: name=Field for one a
// field of the Props writes.
func written(c Comp) string {
	var q []string
	for _, a := range writtenNames(c) {
		for _, at := range c.Attrs {
			if at.Name == a && at.Field != "" {
				a += "=" + at.Field
			}
		}
		q = append(q, fmt.Sprintf("%q", a))
	}
	return strings.Join(q, ", ")
}

// orList is names as a doc lists them: "a, b or c".
func orList(names []string) string {
	if len(names) < 2 {
		return strings.Join(names, "")
	}
	return strings.Join(names[:len(names)-1], ", ") + " or " + names[len(names)-1]
}

// article is "an" before a name that starts with a vowel, else "a".
func article(name string) string {
	if strings.ContainsRune("AEIOU", rune(name[0])) {
		return "an"
	}
	return "a"
}

// str is the field's value as a string.
func str(f Field) string {
	if f.Type == "string" {
		return "p." + f.Name
	}
	return "string(p." + f.Name + ")"
}

func (c Comp) field(name string) Field {
	for _, f := range c.Fields {
		if f.Name == name {
			return f
		}
	}
	if name != "" {
		fail(fmt.Errorf("%s: no field %s", c.Name, name))
	}
	return Field{}
}

// comment writes s as a doc comment, wrapped at 76 columns. A line of s
// starting with a tab is code, kept as it is.
func comment(b *bytes.Buffer, indent, s string) {
	for i, para := range strings.Split(strings.TrimSpace(s), "\n\n") {
		if i > 0 {
			b.WriteString(indent + "//\n")
		}
		if strings.HasPrefix(para, "\t") {
			for _, l := range strings.Split(para, "\n") {
				b.WriteString(indent + "//" + l + "\n")
			}
			continue
		}
		line := ""
		for _, w := range strings.Fields(para) {
			if line != "" && len(indent)*4+3+len(line)+1+len(w) > 76 {
				b.WriteString(indent + "// " + line + "\n")
				line = ""
			}
			if line != "" {
				line += " "
			}
			line += w
		}
		if line != "" {
			b.WriteString(indent + "// " + line + "\n")
		}
	}
}

func lowerName(s string) string {
	return "css" + s
}
